
"""PostgreSQL implementation of the database operations used by DuckMiner."""
import re
from types import SimpleNamespace


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def row_factory(cursor):
    keys = [column.name for column in cursor.description or ()]
    return lambda values: Row(zip(keys, values))


class Database:
    def __init__(self, connection):
        self.connection = connection

    def __enter__(self):
        self.execute('BEGIN IMMEDIATE')
        return self

    def __exit__(self, *exc):
        return self.connection.__exit__(*exc)

    def execute(self, sql, args=()):
        if sql == 'BEGIN IMMEDIATE':
            return self.connection.execute('SELECT pg_advisory_xact_lock(174682201)')
        if sql.startswith('PRAGMA table_info('):
            table = sql.removeprefix('PRAGMA table_info(').removesuffix(')')
            return self.connection.execute(
                'SELECT column_name AS name FROM information_schema.columns '
                'WHERE table_schema=current_schema() AND table_name=%s', (table,))
        if sql.startswith('INSERT OR IGNORE INTO pool'):
            sql = sql.replace('INSERT OR IGNORE', 'INSERT', 1) + ' ON CONFLICT (id) DO NOTHING'
        if sql.startswith('INSERT OR REPLACE INTO limits'):
            sql = ('INSERT INTO limits VALUES(?,?,?) ON CONFLICT (key) '
                   'DO UPDATE SET start=EXCLUDED.start, count=EXCLUDED.count')
        if sql.startswith('INSERT INTO users('):
            cursor = self.connection.execute(sql.replace('?', '%s') + ' RETURNING id', args)
            return SimpleNamespace(lastrowid=cursor.fetchone()[0])
        sql = re.sub(r'\b(?:btc_deposits\.|deposits\.)?rowid\b',
                     lambda m: m[0].replace('rowid', 'id'), sql)
        if sql.lstrip().startswith('CREATE TABLE'):
            sql = re.sub(r'(CREATE TABLE IF NOT EXISTS (?:users|admin_audit)\s*\(\s*id) INTEGER PRIMARY KEY',
                         r'\1 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql)
            sql = re.sub(r'\bINTEGER\b', 'BIGINT', sql)
            sql = re.sub(r'\bBLOB\b', 'BYTEA', sql)
        return self.connection.execute(sql.replace('?', '%s'), args or None)

    def executescript(self, script):
        for statement in script.split(';'):
            statement = statement.strip()
            if statement and not statement.startswith('PRAGMA'):
                self.execute(statement)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


def connect_postgres(url):
    import psycopg
    return Database(psycopg.connect(url, row_factory=row_factory, connect_timeout=10))
